-- director_scopes: which TEAMS a director or HoD moderates (teams-as-categories, slice 2).
--
-- Status: APPLIED LIVE 2026-10-13. Simulated first in rolled-back blocks (super admin writes and reads all;
-- a HoD reads only their own row, is refused an insert with 42501; a duplicate is refused; anon is refused
-- with 42501). The delete refusal was not simulated (the tool holds DELETE for a human); it is the same
-- is_super_admin() check as insert and is visible in pg_policies.
-- Approved by the owner on 2026-10-13 (slices 2 and 3; slice 4 is not approved).
--
-- Why: the five fixed categories (events, welfare, content, operations, labs) are being replaced by the
-- team tree. This adds the new table BESIDE `director_categories`. The old table, its check constraint and
-- its policies are not touched, so nothing is dropped and this is reversible. Slice 3 makes the moderation
-- queue read this table; until then it only records assignments.
--
-- Access, deliberately narrow (it decides who may moderate what):
--   read   : a super admin or HR (is_super_admin() covers both) reads every row; anyone else reads only
--            their own rows (member_id = current_member_id()).
--   insert : super admin or HR only.
--   delete : super admin or HR only.
--   update : nobody (no policy; an assignment is created or removed, never edited).
--   anon   : no privileges at all.
--
-- Grants are explicit. This is NOT public.members, so a table-level grant is fine here, but the default
-- privileges that Supabase gives a new table (every privilege to anon and authenticated) are reduced to
-- the three that the policies can use.
--
-- Undo (human only, destructive): drop table public.director_scopes;

create table if not exists public.director_scopes (
  scope_id    integer generated by default as identity primary key,
  member_id   integer not null references public.members(member_id) on delete cascade,
  team_id     integer not null references public.teams(team_id) on delete cascade,
  assigned_by integer references public.members(member_id),
  assigned_at timestamptz not null default now(),
  constraint director_scopes_member_team_key unique (member_id, team_id)
);

create index if not exists director_scopes_team_id_idx on public.director_scopes (team_id);

alter table public.director_scopes enable row level security;

revoke all on public.director_scopes from anon, authenticated;
grant select, insert, delete on public.director_scopes to authenticated;

create policy director_scopes_select on public.director_scopes
  for select to authenticated
  using (is_super_admin() or member_id = current_member_id());

create policy director_scopes_insert on public.director_scopes
  for insert to authenticated
  with check (is_super_admin());

create policy director_scopes_delete on public.director_scopes
  for delete to authenticated
  using (is_super_admin());

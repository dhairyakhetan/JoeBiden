-- Task tracker, slice 1: tasks, the three roles, visibility and edit rules, comments, change log
-- (owner, 2026-10-19; plan in docs/plans/task-tracker.md).
--
-- Additive only: four new tables, a few helper functions in the `private` schema, policies, grants and triggers.
-- No existing table, column or policy is touched and nothing is dropped. The existing `sops` table (the HoD
-- "SOPs and goals" desk, one assignee per item) is a different feature and is left alone.
--
-- The rules, all enforced here by row-level security, not just by the screens:
--   see    a task: whoever created it, anyone on it (performer, supervisor, spectator, silent or not), and for a TEAM
--          task every active member of its team. A GENERAL task is private to the people on it and its creator, even
--          from HR and super admin.
--   edit   a task (title, description, due date, status) and its people: performers, supervisors and spectators who
--          are not silent. A team member who is not on the task can see a team task but not edit it.
--   comment  the same people who can edit (a comment is an interaction; a silent spectator cannot).
--   create  any active member; a team task only for a team the creator is on, or by a leader. The creator may seed the
--          people of their own new task (they are usually its supervisor and otherwise could not edit what they made).
--   never delete: there is no delete policy on tasks, comments or events.
--
-- `private` helper functions (SECURITY DEFINER, stable): the policies call them so a policy on task_people can read
-- task_people without recursing. `private` is NOT in PostgREST's exposed schemas (public, graphql_public, photobooth,
-- aq_accounts), so none of them is callable as an RPC; authenticated gets USAGE on the schema and EXECUTE on these
-- four only. The advisor's counts of public SECURITY DEFINER functions therefore do not change.
--
-- Derived columns (completed_at, first_due_at, due_moves, updated_at) are written only by triggers; the column grants
-- below leave them out. `first_due_at` and `due_moves` are what the later analytics read: a moved due date still counts
-- as a delay against the first date.
--
-- STATUS: APPLIED LIVE 2026-10-19 (migration tasks_slice1_2026_10_19, then `alter policy tasks_select` for the
-- inline creator test above). Verified in one rolled-back simulation with real member accounts and synthetic task
-- text: the creator seeds people; a performer and a non-silent spectator edit; a silent spectator sees but cannot
-- edit or comment; an unrelated member sees and edits nothing and cannot add themselves; a super admin sees nothing
-- of a general task; a teammate sees a team task but cannot edit or comment; an outsider cannot create a team task
-- for it; kind cannot be changed; due_moves and first_due_at track a moved date; completed_at is set on done and
-- cleared on reopen; the change log records created, people, status, edited and due_moved; anon is refused.
--
-- Undo (human only, destructive): drop table public.task_events, public.task_comments, public.task_people, public.tasks cascade;

create table if not exists public.tasks (
  task_id      integer generated by default as identity primary key,
  uuid         uuid not null default gen_random_uuid() unique,
  title        text not null check (char_length(btrim(title)) between 3 and 200),
  description  text not null default '' check (char_length(description) <= 4000),
  kind         text not null check (kind in ('team', 'general')),
  team_id      integer references public.teams(team_id),
  created_by   integer not null references public.members(member_id),
  due_at       timestamptz,
  first_due_at timestamptz,
  due_moves    integer not null default 0,
  status       text not null default 'open' check (status in ('open', 'in_progress', 'blocked', 'done')),
  completed_at timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint tasks_team_matches_kind check ((kind = 'team') = (team_id is not null))
);
create index if not exists tasks_team_id_idx on public.tasks (team_id);
create index if not exists tasks_created_by_idx on public.tasks (created_by);

create table if not exists public.task_people (
  task_id   integer not null references public.tasks(task_id) on delete cascade,
  member_id integer not null references public.members(member_id),
  role      text not null check (role in ('performer', 'supervisor', 'spectator')),
  silent    boolean not null default false,
  added_by  integer references public.members(member_id),
  added_at  timestamptz not null default now(),
  primary key (task_id, member_id),
  constraint task_people_silent_spectators_only check (not silent or role = 'spectator')
);
create index if not exists task_people_member_idx on public.task_people (member_id);

create table if not exists public.task_comments (
  comment_id bigint generated by default as identity primary key,
  task_id    integer not null references public.tasks(task_id) on delete cascade,
  member_id  integer not null references public.members(member_id),
  body       text not null check (char_length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists task_comments_task_idx on public.task_comments (task_id, created_at);

create table if not exists public.task_events (
  event_id        bigint generated by default as identity primary key,
  task_id         integer not null references public.tasks(task_id) on delete cascade,
  actor_member_id integer references public.members(member_id),
  kind            text not null,
  note            text,
  at              timestamptz not null default now()
);
create index if not exists task_events_task_idx on public.task_events (task_id, at);

-- Helpers ---------------------------------------------------------------------------------------------------------

create or replace function private.task_can_see(p_task integer) returns boolean
language sql stable security definer set search_path to 'public', 'pg_temp' as $$
  select exists (
    select 1 from public.tasks t
     where t.task_id = p_task
       and public.current_member_id() is not null
       and (
         t.created_by = public.current_member_id()
         or exists (select 1 from public.task_people p where p.task_id = t.task_id and p.member_id = public.current_member_id())
         or (t.kind = 'team' and exists (
               select 1 from public.team_members tm
                where tm.team_id = t.team_id and tm.member_id = public.current_member_id()
                  and tm.is_active is true and tm.left_at is null))
       )
  );
$$;

create or replace function private.task_can_edit(p_task integer) returns boolean
language sql stable security definer set search_path to 'public', 'pg_temp' as $$
  select exists (
    select 1 from public.task_people p
     where p.task_id = p_task
       and p.member_id = public.current_member_id()
       and (p.role in ('performer', 'supervisor') or (p.role = 'spectator' and not p.silent))
  );
$$;

-- The creator of a task may add its people while nobody is on it yet.
create or replace function private.task_creator_seeding(p_task integer) returns boolean
language sql stable security definer set search_path to 'public', 'pg_temp' as $$
  select exists (
    select 1 from public.tasks t
     where t.task_id = p_task
       and t.created_by = public.current_member_id()
       and public.current_member_id() is not null
       and not exists (select 1 from public.task_people p where p.task_id = t.task_id)
  );
$$;

create or replace function private.task_creator_may_use_team(p_team integer) returns boolean
language sql stable security definer set search_path to 'public', 'pg_temp' as $$
  select public.current_member_id() is not null and (
    public.is_director()
    or exists (select 1 from public.team_members tm
                where tm.team_id = p_team and tm.member_id = public.current_member_id()
                  and tm.is_active is true and tm.left_at is null)
  );
$$;

-- Triggers --------------------------------------------------------------------------------------------------------

create or replace function private.tasks_before_write() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if tg_op = 'INSERT' then
    new.first_due_at := new.due_at;
    new.due_moves := 0;
    new.status := 'open';
    new.completed_at := null;
  else
    if new.status is distinct from old.status then
      new.completed_at := case when new.status = 'done' then now() end;
    end if;
    if new.due_at is distinct from old.due_at then
      if new.first_due_at is null then new.first_due_at := new.due_at; end if;
      if old.due_at is not null and new.due_at is not null then new.due_moves := old.due_moves + 1; end if;
    end if;
  end if;
  new.updated_at := now();
  return new;
end $$;

create or replace function private.tasks_log() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare
  v_id integer := public.current_member_id();
begin
  if tg_op = 'INSERT' then
    insert into public.task_events (task_id, actor_member_id, kind, note) values (new.task_id, v_id, 'created', new.kind);
    return new;
  end if;
  if new.status is distinct from old.status then
    insert into public.task_events (task_id, actor_member_id, kind, note) values (new.task_id, v_id, 'status', old.status || ' to ' || new.status);
  end if;
  if new.due_at is distinct from old.due_at then
    insert into public.task_events (task_id, actor_member_id, kind, note)
    values (new.task_id, v_id, 'due_moved', coalesce(to_char(old.due_at at time zone 'Asia/Kolkata', 'YYYY-MM-DD'), 'none') || ' to ' || coalesce(to_char(new.due_at at time zone 'Asia/Kolkata', 'YYYY-MM-DD'), 'none'));
  end if;
  if new.title is distinct from old.title or new.description is distinct from old.description then
    insert into public.task_events (task_id, actor_member_id, kind) values (new.task_id, v_id, 'edited');
  end if;
  return new;
end $$;

create or replace function private.task_people_before_insert() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  new.added_by := public.current_member_id();
  new.added_at := now();
  return new;
end $$;

create or replace function private.task_people_log() returns trigger
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare
  v_id integer := public.current_member_id();
  v_row public.task_people;
  v_name text;
begin
  v_row := case when tg_op = 'DELETE' then old else new end;
  select full_name into v_name from public.members where member_id = v_row.member_id;
  if tg_op = 'INSERT' then
    insert into public.task_events (task_id, actor_member_id, kind, note)
    values (v_row.task_id, v_id, 'person_added', coalesce(v_name, 'a member') || ' as ' || v_row.role || case when v_row.silent then ' (silent)' else '' end);
  elsif tg_op = 'DELETE' then
    insert into public.task_events (task_id, actor_member_id, kind, note)
    values (v_row.task_id, v_id, 'person_removed', coalesce(v_name, 'a member') || ' as ' || v_row.role);
  elsif new.role is distinct from old.role or new.silent is distinct from old.silent then
    insert into public.task_events (task_id, actor_member_id, kind, note)
    values (v_row.task_id, v_id, 'role_changed', coalesce(v_name, 'a member') || ' now ' || new.role || case when new.silent then ' (silent)' else '' end);
  end if;
  return v_row;
end $$;

create or replace trigger tasks_before_write before insert or update on public.tasks
  for each row execute function private.tasks_before_write();
create or replace trigger tasks_log after insert or update on public.tasks
  for each row execute function private.tasks_log();
create or replace trigger task_people_before_insert before insert on public.task_people
  for each row execute function private.task_people_before_insert();
create or replace trigger task_people_log after insert or update or delete on public.task_people
  for each row execute function private.task_people_log();

-- Row-level security ------------------------------------------------------------------------------------------------

alter table public.tasks enable row level security;
alter table public.task_people enable row level security;
alter table public.task_comments enable row level security;
alter table public.task_events enable row level security;

-- The creator test is written inline, not only inside task_can_see(): INSERT ... RETURNING checks the select policy
-- against the row being inserted, and the helper's own query cannot see that row yet (found in simulation).
create policy tasks_select on public.tasks for select to authenticated
  using (created_by = public.current_member_id() or private.task_can_see(task_id));
create policy tasks_insert on public.tasks for insert to authenticated
  with check (created_by = public.current_member_id()
              and (kind = 'general' or private.task_creator_may_use_team(team_id)));
create policy tasks_update on public.tasks for update to authenticated
  using (private.task_can_edit(task_id)) with check (private.task_can_edit(task_id));

create policy task_people_select on public.task_people for select to authenticated
  using (private.task_can_see(task_id));
create policy task_people_insert on public.task_people for insert to authenticated
  with check (private.task_can_edit(task_id) or private.task_creator_seeding(task_id));
create policy task_people_update on public.task_people for update to authenticated
  using (private.task_can_edit(task_id)) with check (private.task_can_edit(task_id));
create policy task_people_delete on public.task_people for delete to authenticated
  using (private.task_can_edit(task_id));

create policy task_comments_select on public.task_comments for select to authenticated
  using (private.task_can_see(task_id));
create policy task_comments_insert on public.task_comments for insert to authenticated
  with check (member_id = public.current_member_id() and private.task_can_edit(task_id));

create policy task_events_select on public.task_events for select to authenticated
  using (private.task_can_see(task_id));

-- Grants: explicit, column by column. anon gets nothing. No delete anywhere except removing a person from a task.

revoke all on public.tasks, public.task_people, public.task_comments, public.task_events from anon, authenticated;

grant select on public.tasks, public.task_people, public.task_comments, public.task_events to authenticated;
grant insert (title, description, kind, team_id, created_by, due_at) on public.tasks to authenticated;
grant update (title, description, due_at, status) on public.tasks to authenticated;
grant insert (task_id, member_id, role, silent) on public.task_people to authenticated;
grant update (role, silent) on public.task_people to authenticated;
grant delete on public.task_people to authenticated;
grant insert (task_id, member_id, body) on public.task_comments to authenticated;

grant usage on schema private to authenticated;
revoke all on function private.task_can_see(integer), private.task_can_edit(integer),
  private.task_creator_seeding(integer), private.task_creator_may_use_team(integer) from public, anon;
grant execute on function private.task_can_see(integer), private.task_can_edit(integer),
  private.task_creator_seeding(integer), private.task_creator_may_use_team(integer) to authenticated;
